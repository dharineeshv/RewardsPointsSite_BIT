export function getCampusMessMenu(hostel = 'boys', dateString) {
  let targetDate = new Date();
  if (dateString) {
    const parts = dateString.split('-');
    if (parts.length === 3) {
      targetDate = new Date(parseInt(parts[0], 10), parseInt(parts[1], 10) - 1, parseInt(parts[2], 10));
    }
  }

  const y = targetDate.getFullYear();
  const m = String(targetDate.getMonth() + 1).padStart(2, '0');
  const d = String(targetDate.getDate()).padStart(2, '0');
  const key = `${y}-${m}-${d}`;

  const daysOfWeek = ['Sunday', 'Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday'];
  const dayName = daysOfWeek[targetDate.getDay()];

  const dataset = hostel === 'boys' ? BOYS_MESS_SEPTEMBER_2026 : GIRLS_MESS_SEPTEMBER_2026;
  const match = dataset[key] || WEEKLY_MESS_TEMPLATE[targetDate.getDay()];

  const now = new Date();
  const currentHour = now.getHours();
  const currentMin = now.getMinutes();
  const totalMinutes = currentHour * 60 + currentMin;

  let currentMealType = 'Breakfast';
  let mealStartTime = '07:30 AM';
  let mealEndTime = '09:00 AM';
  let activeItems = match.breakfast || [];

  if (totalMinutes >= 7 * 60 && totalMinutes < 10 * 60 + 30) {
    currentMealType = 'Breakfast';
    mealStartTime = '07:30 AM';
    mealEndTime = '09:00 AM';
    activeItems = match.breakfast || [];
  } else if (totalMinutes >= 10 * 60 + 30 && totalMinutes < 15 * 60 + 30) {
    currentMealType = 'Lunch';
    mealStartTime = '12:00 PM';
    mealEndTime = '02:00 PM';
    activeItems = match.lunch || [];
  } else if (totalMinutes >= 15 * 60 + 30 && totalMinutes < 22 * 60) {
    currentMealType = 'Dinner';
    mealStartTime = '07:00 PM';
    mealEndTime = '08:30 PM';
    activeItems = match.dinner || [];
  } else {
    currentMealType = 'Upcoming Breakfast';
    mealStartTime = '07:30 AM';
    mealEndTime = '09:00 AM';
    activeItems = match.breakfast || [];
  }

  return {
    success: true,
    hostel,
    date: key,
    day: match.day || dayName,
    isOfficialSeptemberSchedule: !!dataset[key],
    current_meal: {
      meal_type: currentMealType,
      start_time: mealStartTime,
      end_time: mealEndTime,
      items: activeItems
    },
    full_menu: {
      breakfast: match.breakfast || [],
      lunch: match.lunch || [],
      dinner: match.dinner || []
    }
  };
}
